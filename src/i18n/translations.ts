export function formatEffectList(effects: ResourceEffects, lang: Lang): string[] {
  const t = TRANSLATIONS[lang];
  const items: string[] = [];
  const push = (val: number | undefined, label: string, suffix = '') => {
    if (val === undefined || val === 0) return;
    const sign = val > 0 ? '+' : '';
    items.push(`${sign}${val.toLocaleString('en-US')}${suffix} ${label}`);
  };
  push(effects.population, t.metricPopulation);
  push(effects.food, t.metricFood, '%');
  push(effects.water, t.metricWater, '%');
  push(effects.energy, t.metricEnergy, '%');
  push(effects.treasury, t.metricTreasury);
  push(effects.health, t.metricHealth, '%');
  push(effects.education, t.metricEducation, '%');
  push(effects.happiness, t.metricHappiness, '%');
  return items;
}

export function getCitizenRank(votesCount: number, lang: Lang): string {
  if (lang === 'ar') {
    if (votesCount >= 20) return 'حكيم الجزيرة';
    if (votesCount >= 10) return 'معماري أول';
    if (votesCount >= 3) return 'مستوطن فاعل';
    return 'رائد جديد';
  }
  if (votesCount >= 20) return 'Island Elder';
  if (votesCount >= 10) return 'Master Architect';
  if (votesCount >= 3) return 'Active Settler';
  return 'New Pioneer';
}
